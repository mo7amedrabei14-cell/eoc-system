/**
 * Translate a string from Arabic to English if language is 'en'.
 * @param {string} text - The Arabic string to translate.
 * @param {string} language - The current language ('ar' or 'en').
 * @returns {string} The translated string if language is 'en', otherwise the original.
 */
function translate(text, language) {
  if (typeof text !== 'string') return text;
  if (language !== 'en') return text;
  return ENGLISH_UI[text] || text; // fallback to original if not found
}

