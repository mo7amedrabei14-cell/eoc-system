-- الجذر: سجل القوة البشرية يظهر "في مهمة حاليًا" = 0 رغم وجود متطوعين.
--
-- السبب الجذري: حقل return_status في mission_participants كان قد اتضبط على
-- 'تم انتهاء مهمتة' لمشاركين داخل مهام ما زالت نشطة (Under Review / Approved).
-- قاعدة البيانات هي مصدر الحقيقة: المدخل الوحيد لحالة "في مهمة حاليًا" هو
-- تطابق مهمة غير منتهية مع مشارك لم يُسجَّل عودته.
--
-- هذا الملف يُعيد محاذاة return_status مع حالة المهمة الموجودة فعلاً، بنفس
-- القاعدة المعتمدة في الكود (backend): المهمة المنتهية فقط => 'تم انتهاء مهمتة'
-- وأي مهمة أخرى غير منتهية => 'مازال بالمهمة'.
--
-- آمن للإعادة (idempotent): يُحدِّث الصفوف المتناقضة فقط؛ وإعادة تشغيله لا
-- تغيّر شيئاً. لا يحذف أي بيانات ولا يمس المشاركين ولا المهام.
-- ============================================================================

BEGIN;

-- 1) مشاركين داخل مهام ما زالت نشطة (غير منتهية) لكن حالتهم "انتهت مهمته"
--    => كانت بيانات متعارضة مع حالة المهمة (مصدر الحقيقة) => تعود "مازال بالمهمة".
UPDATE mission_participants mp
SET return_status = 'مازال بالمهمة'
FROM missions m
WHERE m.mission_id = mp.mission_id
  AND mp.return_status = 'تم انتهاء مهمتة'
  AND m.status NOT IN ('Completed', 'مكتملة', 'Closed', 'Canceled', 'Cancelled');

-- 2) العكس: مشاركين داخل مهام منتهية/مغلقة لكن حالتهم "مازال بالمهمة"
--    => تعود "تم انتهاء مهمتة" (مصدر الحقيقة هو حالة المهمة).
UPDATE mission_participants mp
SET return_status = 'تم انتهاء مهمتة'
FROM missions m
WHERE m.mission_id = mp.mission_id
  AND mp.return_status = 'مازال بالمهمة'
  AND m.status IN ('Completed', 'مكتملة', 'Closed', 'Canceled', 'Cancelled');

-- 3) بعد المحاذاة لا يُسمح بالتناقض مستقبلاً من طرف النظام:
--    أي مشارك يُدخل في مهمة غير منتهية لا بد أن يظل 'مازال بالمهمة'
--    (وهو سلوك الكود بالفعل؛ هذا تأكيد لمصدر الحقيقة).

COMMIT;